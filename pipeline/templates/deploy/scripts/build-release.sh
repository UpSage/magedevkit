#!/usr/bin/env bash
# @@HEADER@@
#
# Builds a Magento release bundle — the single source of truth for that.
# deploy/buildspec.yml runs it in CodeBuild inside the same php image the box
# runs; the pipeline wizard's local build test runs it the same way.
#
# Never talks to a database: composer install --no-dev, setup:di:compile and
# setup:static-content:deploy all work from app/etc/config.php (which must be
# committed, with its `scopes` section) and a throwaway env.php.
#
# Output: .build/release/ — the code, deploy/, appspec.yml at the root (where
# CodeDeploy looks for it) and release.env (image tag + commit).
#
#   build-release.sh [--source DIR] [--output DIR] [--image-tag TAG] [--registry HOST]

set -euo pipefail

SOURCE_DIR="$(pwd)"
OUTPUT_DIR=""
IMAGE_TAG="${IMAGE_TAG:-}"
ECR_REGISTRY="${ECR_REGISTRY:-}"
ECR_PREFIX="${ECR_PREFIX:-}"   # <app>-<env>: the box pulls $ECR_REGISTRY/$ECR_PREFIX-php|nginx
STATIC_LOCALES="${STATIC_LOCALES:-en_US}"
BUILD_JOBS="${BUILD_JOBS:-$(nproc 2>/dev/null || echo 1)}"

while [ $# -gt 0 ]; do
    case "$1" in
        --source) SOURCE_DIR="$2"; shift 2 ;;
        --output) OUTPUT_DIR="$2"; shift 2 ;;
        --image-tag) IMAGE_TAG="$2"; shift 2 ;;
        --registry) ECR_REGISTRY="$2"; shift 2 ;;
        *) echo "[build-release] unknown argument: $1" >&2; exit 2 ;;
    esac
done

SOURCE_DIR="$(cd "$SOURCE_DIR" && pwd)"
OUTPUT_DIR="${OUTPUT_DIR:-$SOURCE_DIR/.build}"
RELEASE_DIR="$OUTPUT_DIR/release"
log() { echo "[build-release] $*"; }
fail() { echo "[build-release] ERROR: $*" >&2; exit 1; }

for f in composer.json composer.lock app/etc/config.php deploy/appspec.yml; do
    [ -e "$SOURCE_DIR/$f" ] || fail "$f not found in $SOURCE_DIR."
done
grep -q "'scopes'" "$SOURCE_DIR/app/etc/config.php" \
    || fail "app/etc/config.php has no 'scopes' section — static content can't be deployed without a database. Run: bin/magento app:config:dump scopes themes, then commit it."

COMMIT="no-git"
if git -C "$SOURCE_DIR" rev-parse --short HEAD >/dev/null 2>&1; then
    COMMIT="$(git -C "$SOURCE_DIR" rev-parse --short HEAD)"
elif [ -n "${CODEBUILD_RESOLVED_SOURCE_VERSION:-}" ]; then
    COMMIT="${CODEBUILD_RESOLVED_SOURCE_VERSION:0:7}"
fi
log "source $SOURCE_DIR, commit $COMMIT"

# Everything happens in a scratch copy — the source is only read.
WORKSPACE="$(mktemp -d "${TMPDIR:-/tmp}/build-release.XXXXXX")"
trap 'rm -rf "$WORKSPACE"' EXIT
rsync -a \
    --exclude='/.git/' --exclude='/.build/' --exclude='/app/etc/env.php*' --exclude='/app/etc/platform/' \
    --exclude='/auth.json' --exclude='/vendor/' --exclude='/generated/' --exclude='/var/' \
    --exclude='/pub/static/' --exclude='/pub/media/' --exclude='node_modules/' \
    --exclude='/deploy/infra/' \
    "$SOURCE_DIR/" "$WORKSPACE/"
cd "$WORKSPACE"

log "composer install --no-dev"
composer install --no-dev --optimize-autoloader --no-interaction --prefer-dist --no-progress

# Patches in patches/*.patch (if the project keeps any there).
for p in patches/*.patch; do
    [ -e "$p" ] || continue
    log "applying $p"
    patch -p1 --forward --silent < "$p" || fail "patch $p didn't apply."
done

log "throwaway app/etc/env.php for the compile steps"
cat > app/etc/env.php <<EOF
<?php
// Generated by deploy/scripts/build-release.sh for the compile steps only —
// deleted before the release is assembled.
return [
    'MAGE_MODE' => 'production',
    'crypt' => ['key' => '$(head -c 32 /dev/urandom | od -An -tx1 | tr -d " \n")'],
    'system' => ['default' => ['dev' => ['js' => ['minify_files' => '1'], 'css' => ['minify_files' => '1']]]],
];
EOF

log "setup:di:compile"
php -d memory_limit=-1 bin/magento setup:di:compile --no-ansi
log "setup:static-content:deploy ($STATIC_LOCALES, $BUILD_JOBS jobs)"
# shellcheck disable=SC2086
php -d memory_limit=-1 bin/magento setup:static-content:deploy -f --no-ansi --jobs="$BUILD_JOBS" $STATIC_LOCALES
rm -f app/etc/env.php

log "assembling $RELEASE_DIR"
rm -rf "$RELEASE_DIR"
mkdir -p "$RELEASE_DIR"
rsync -a --exclude='/var/' --exclude='*.sql' --exclude='*.sql.gz' "$WORKSPACE/" "$RELEASE_DIR/"
cp deploy/appspec.yml "$RELEASE_DIR/appspec.yml"
chmod +x "$RELEASE_DIR"/deploy/scripts/render-env "$RELEASE_DIR"/deploy/scripts/deploy \
    "$RELEASE_DIR"/deploy/scripts/box "$RELEASE_DIR"/deploy/scripts/hooks/*.sh
cat > "$RELEASE_DIR/release.env" <<EOF
ECR_REGISTRY=$ECR_REGISTRY
ECR_PREFIX=$ECR_PREFIX
IMAGE_TAG=$IMAGE_TAG
COMMIT=$COMMIT
BUILT_AT=$(date -u +%FT%TZ)
EOF
log "done: $(find "$RELEASE_DIR/pub/static" -type f | wc -l) static files, $(find "$RELEASE_DIR/generated" -type f | wc -l) generated files"
