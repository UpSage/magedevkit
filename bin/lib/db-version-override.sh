# Local MariaDB version allowance — sourced by bin/lib/setup-engine.sh and
# bin/lib/refresh-engine.sh. Never invoke this file directly.
#
# Magento's setup:install / setup:upgrade refuse to run unless the database
# version matches one of SqlVersionProvider's supportedVersionPatterns in
# app/etc/di.xml. That file is committed to the project repo and can lag
# behind the Magento patch actually installed (e.g. a 2.4.8-p5 project still
# carrying 2.4.8's di.xml, which only allows MariaDB 11.4 while p5 supports
# 11.8) — and the m2 catalog pins MARIADB_VERSION from Adobe's requirements
# for the installed patch, so the two disagree.
#
# Rather than editing the committed di.xml, this writes app/etc/platform/
# di.xml: Magento's primary config loader merges app/etc/di.xml with every
# app/etc/*/di.xml, and array items merge by name, so the item below adds
# the running MariaDB version without replacing the project's own list. The
# path goes into .git/info/exclude (per-clone, never committed), so it stays
# local and never reaches another environment.
#
# Expects the caller to have already defined: log(), PLATFORM_DIR, and
# MARIADB_VERSION (from the env file).

write_db_version_override() {
    local magento_dir="${MAGENTO_DIR:-$PLATFORM_DIR/../magento}" dir file pattern
    dir="$magento_dir/app/etc/platform"
    file="$dir/di.xml"
    [ -d "$magento_dir/app/etc" ] || return 0

    # "11.8" -> ^11\.8\.   "11" -> ^11\.   anything else (e.g. "lts") can't
    # be turned into a version pattern, so leave the project's list alone.
    if [[ ! "${MARIADB_VERSION:-}" =~ ^[0-9]+(\.[0-9]+)?$ ]]; then
        log "⚠ MARIADB_VERSION='${MARIADB_VERSION:-}' isn't a numeric version — not adding a local Magento DB version allowance."
        rm -f "$file"
        return 0
    fi
    pattern="^${MARIADB_VERSION//./\\.}\\."

    mkdir -p "$dir"
    cat > "$file" <<EOF
<?xml version="1.0"?>
<!--
    Generated by MageDevKit (bin/lib/db-version-override.sh) from MARIADB_VERSION
    in the instance's env file — local only (listed in .git/info/exclude),
    rewritten on every setup/refresh. Do not edit or commit.
-->
<config xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="urn:magento:framework:ObjectManager/etc/config.xsd">
    <type name="Magento\Framework\DB\Adapter\SqlVersionProvider">
        <arguments>
            <argument name="supportedVersionPatterns" xsi:type="array">
                <item name="Platform-MariaDB-${MARIADB_VERSION}" xsi:type="string">${pattern}</item>
            </argument>
        </arguments>
    </type>
</config>
EOF

    if [ -d "$magento_dir/.git" ]; then
        local exclude="$magento_dir/.git/info/exclude"
        mkdir -p "$(dirname "$exclude")"
        grep -qxF '/app/etc/platform/' "$exclude" 2>/dev/null || echo '/app/etc/platform/' >> "$exclude"
    fi
    log "✓ Magento allows MariaDB $MARIADB_VERSION (app/etc/platform/di.xml)"
}
