# Pipeline wizard engine — sourced by bin/local/pipeline once it has resolved
# ENV_FILE. Never invoke this file directly.
#
# Makes an instance's Magento repo pipeline-ready: renders the pipeline kit
# (pipeline/templates/ in this repo, plus the instance's own container files
# and version pins) into magento/deploy/ and magento/.platform/stack.env,
# validates it, and commits it on a new local branch. It never pushes — you
# push the branch with the store, and the AWS side comes from the provision
# wizard (planned; not in this version).
#
# deploy/pipeline.json records the template version, the targets and a
# checksum of every generated file, so a rerun can tell files it may update
# from files someone edited by hand (those are kept unless you choose to
# replace them).
#
# Answers are saved in the instance .env as PIPELINE_* and come back as the
# defaults. Non-interactive use: PRESET_PIPELINE_<KEY> for any answer, e.g.
# PRESET_PIPELINE_ENV=dev PRESET_PIPELINE_DOMAIN=dev.example.com.
#
# Expects the caller to have already defined: log(), fail(), ui_* helpers,
# set_env_var, esc_sed, PLATFORM_DIR, ENV_FILE, MAGENTO_DIR.

