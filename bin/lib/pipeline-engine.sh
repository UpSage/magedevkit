# answer KEY DEFAULT — PRESET_PIPELINE_<KEY>, else the saved PIPELINE_<KEY>,
# else DEFAULT (what the prompt shows as its default).
pl_saved() {
    local p="PRESET_PIPELINE_$1" s="PIPELINE_$1"
    if [ -n "${!p:-}" ]; then printf '%s' "${!p}"; elif [ -n "${!s:-}" ]; then printf '%s' "${!s}"; else printf '%s' "$2"; fi
}
pl_preset() { local p="PRESET_PIPELINE_$1"; [ -n "${!p:-}" ]; }

# pl_ask KEY LABEL DEFAULT REGEX HINT — a validated text answer, saved to .env.
pl_ask() {
    local key="$1" label="$2" def regex="$4" hint="$5" v
    def="$(pl_saved "$key" "$3")"
    while true; do
        if pl_preset "$key"; then v="$def"; else v="$(prompt_value "$label [$def]" 0)"; v="${v:-$def}"; fi
        if [[ "$v" =~ $regex ]]; then break; fi
        pl_preset "$key" && fail "PRESET_PIPELINE_$key='$v' isn't valid: $hint"
        ui_interactive || fail "$label: '$v' isn't valid ($hint) — set PRESET_PIPELINE_$key, or run this in a terminal."
        log "⚠ '$v' isn't valid: $hint" >&2
    done
    set_env_var "$ENV_FILE" "PIPELINE_$key" "$v"
    printf '%s' "$v"
}

# pl_choose KEY QUESTION DEFAULT OPTION… — one of the options (the value is the
# text before " — "), saved to .env.
pl_choose() {
    local key="$1" q="$2" def i n v opts=()
    def="$(pl_saved "$key" "$3")"
    shift 3
    if pl_preset "$key"; then v="$def"; else
        n=1
        for ((i = 1; i <= $#; i++)); do
            opts+=("${!i}$([ "${!i%% — *}" = "$def" ] && printf ' (default)')")
            [ "${!i%% — *}" = "$def" ] && n="$i"
        done
        i="$(prompt_menu "$q" "$n" "${opts[@]}")"
        v="${!i}"
        v="${v%% — *}"
    fi
    set_env_var "$ENV_FILE" "PIPELINE_$key" "$v"
    printf '%s' "$v"
}

# aws with the chosen profile, short timeout, no pager; empty output on error.
# Skipped (fails at once) when the chosen profile isn't one of yours — the
# CLI would otherwise spend its timeout looking for credentials.
aws_q() {
    command -v aws >/dev/null 2>&1 || return 1
    printf '%s\n' "${PROFILES[@]}" | grep -qxF -- "$AWS_PROFILE_SEL" || return 1
    AWS_PAGER="" timeout 25 aws --profile "$AWS_PROFILE_SEL" --region "$AWS_REGION_SEL" "$@" 2>/dev/null
}


# Header line put in every generated file.
kit_header() {
    printf 'Generated by MageDevKit (pipeline kit v%s) for %s. Update with: mdk pipeline-wizard — hand edits are kept unless you choose to replace them.' \
        "$KIT_VERSION" "$APP"
}

# Renders template $1 to stage path $2, filling @@KEY@@ from KIT[KEY].
declare -A KIT=()
KIT_SED=()  # the sed expressions, built once (escaping per file was slow)
kit_render() {
    local src="$1" dst="$KIT_STAGE/$2" k
    mkdir -p "$(dirname "$dst")"
    if [ "${#KIT_SED[@]}" = 0 ]; then
        for k in "${!KIT[@]}"; do KIT_SED+=(-e "s/@@${k}@@/$(esc_sed "${KIT[$k]}")/g"); done
    fi
    sed "${KIT_SED[@]}" "$src" > "$dst"
    if grep -qE '@@[A-Z_]+@@' "$dst"; then
        fail "Template $src left a placeholder unfilled: $(grep -oE '@@[A-Z_]+@@' "$dst" | sort -u | tr '\n' ' ')"
    fi
    [ -x "$src" ] && chmod +x "$dst"
    return 0
}

# Copies one of this repo's own container/config files into the stage with a
# header comment ($3 = comment prefix).
kit_seed() {
    local src="$PLATFORM_DIR/$1" dst="$KIT_STAGE/$2"
    [ -f "$src" ] || fail "$1 is missing from the wizard repo."
    mkdir -p "$(dirname "$dst")"
    { printf '%s %s\n%s Source: %s in MageDevKit.\n\n' "$3" "$(kit_header)" "$3" "$1"; cat "$src"; } > "$dst"
}

