# The heavy check: what CodeBuild will do, on this machine.
build_test() {
    local tag="pipeline-test/${APP}-php:local" out
    out="$(mktemp -d)"
    docker build --quiet \
        --build-arg PHP_VERSION="$PHP_VERSION" --build-arg DEBIAN_RELEASE="$DEBIAN_RELEASE" \
        --build-arg COMPOSER_VERSION="$COMPOSER_VERSION" -t "$tag" "$MAGENTO_DIR/deploy/docker/php" >/dev/null || return 1
    COMPOSER_AUTH="$(cat "$MAGENTO_DIR/auth.json" 2>/dev/null || printf '{}')" docker run --rm \
        -e COMPOSER_AUTH -e COMPOSER_ALLOW_SUPERUSER=1 -e STATIC_LOCALES="$STATIC_LOCALES" \
        -v "$MAGENTO_DIR:/src:ro" -v "$out:/out" -w /src \
        --entrypoint bash "$tag" deploy/scripts/build-release.sh --output /out || { rm -rf "$out"; return 1; }
    log "Release built: $(du -sh "$out/release" | cut -f1)"
    rm -rf "$out"
}
BUILD_TEST=no
if pl_preset BUILD_TEST; then BUILD_TEST="$(pl_saved BUILD_TEST no)"
elif docker info >/dev/null 2>&1 && prompt_yes_no 'Also build a release now, exactly as CodeBuild will (php image, composer --no-dev, DI compile, static content)? It takes 10–20 minutes.' N; then
    BUILD_TEST=yes
fi
if [ "$BUILD_TEST" = yes ]; then
    ui_task "Building a release like CodeBuild will" build_test \
        || fail "The release build failed — CodeBuild would fail the same way (see the output above)."
fi

